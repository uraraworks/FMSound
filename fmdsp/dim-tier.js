// 段階的暗色表示(通常/ミュート/未使用)の共通定義。
//
// 2026-08-17 利用者指摘への対応: 従来はパレット番号を付け替えて暗さを表現していた
// (例: 鍵盤ハイライトを通常時色6(緑)からミュート時色8(青)へ差し替え)。しかし
// FMDSPの既定パレットには「色相を保ったまま暗い緑」が存在しないため、番号を
// 付け替えると色相そのものが変わってしまい、「暗くなった」ではなく「別の色に
// なった」と見えてしまう(利用者指摘: 「通常が緑に対して暗い版は青色になってます。
// 暗くなった感じには見えない」)。
//
// 対策(利用者判断): 色番号を差し替えるのをやめ、「元の色 x 係数」で暗くする
// (色相を保つ)方式に統一する。係数は fmdsp/vram.js の Vram#toImageData() が
// パレットRGBへ最終展開する瞬間に掛ける(そこが「パレット番号→RGB」の唯一の
// 変換点であるため、ここでの一括処理が最も素直で追いやすい。個々の描画関数
// (drawTrackRow/drawLevelMeters等)は「このピクセルは今どの段階か」を
// vram.setTier()で申告するだけでよく、色番号自体は今までどおり通常色
// (COLOR_LABEL/COLOR_TYPE/COLOR_KEY_HILITE/COLOR_1等)を使い続ける)。
//
// 係数の選定(通常1.0 / ミュート0.5 / 未使用0.25):
//   - 通常=1.0は当然(無変換)。
//   - ミュート=0.5: 「半分暗くなった」と直感的にわかりやすい値。実際に
//     tools/verify_help_screenshots.mjs 等でレンダリングして目視確認したところ、
//     これより下げるとTN:/Vl:等の細い文字(5x6フォント、1px線)が背景色(黒)に
//     沈んで判読しにくくなり始めたため、視認性を保てる下限として採用した。
//   - 未使用=0.25: ミュートよりもう一段暗いことが分かる必要がある。0.5のさらに
//     半分(=0.25)にすることで「ミュート:通常」と同じ比率(1:2)を
//     「未使用:ミュート」にも適用し、「もう一段、同じ調子で暗くなった」という
//     関係を一貫させた(0.5だけ下げて0.4等の中途半端な値にするより、比率が
//     揃っている方が「規則的に暗くなっている」と直感的に伝わると判断)。
//   - 黒(index0、輝度0)には掛けても常に0のままなので、背景と前景の区別は
//     どの段階でも失われない。
//
// TIER_NORMAL/MUTED/UNUSEDの値は Vram#setTier() に渡すindexと、
// DIM_FACTORS配列のindexに完全に一致させる(DIM_FACTORS[tier]がそのまま
// toImageData内の乗数になる。ずれると意味が変わってしまうため、この対応関係を
// 変える場合は必ず両方を同時に直すこと)。
export const TIER_NORMAL = 0;
export const TIER_MUTED = 1;
export const TIER_UNUSED = 2;

export const DIM_FACTORS = [1.0, 0.5, 0.25];

// data配下のmuted/unusedフラグ(bool)から段階indexを決める共通ヘルパー。
// 優先順位: 未使用 > ミュート > 通常(曲がそもそも使っていないパートを利用者が
// さらにミュートしても、元々鳴らないので見た目を変える必要が無い。
// fmdsp/trackrow.js drawTrackRowの旧コメントより方針を踏襲)。
export function tierFor(muted, unused) {
  if (unused) return TIER_UNUSED;
  if (muted) return TIER_MUTED;
  return TIER_NORMAL;
}
